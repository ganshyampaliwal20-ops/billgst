import jsPDF from 'jspdf';
import QRCode from 'qrcode';
import autoTable from 'jspdf-autotable';
import { toast } from 'react-hot-toast';
import { downloadAndShareFile } from './utils';

// Helper to check premium status
export const isUserPremium = (businessDetails) => {
    let premium = ['BASIC_30', 'PREMIUM_99', 'YEARLY_299', 'LIFETIME'].includes(businessDetails?.plan_type);
    if (!premium && businessDetails?.created_at) {
        const createdDate = new Date(businessDetails.created_at);
        const oneMonthLater = new Date(createdDate.getTime() + 30 * 24 * 60 * 60 * 1000);
        if (new Date() <= oneMonthLater) premium = true;
    }
    return premium;
};

// Simplified free branding for e-way bill
export const drawFreeBranding = async (doc, isThermal, pageWidth, pageHeight, startY) => {
    try {
        let yPos = startY || (pageHeight - 10);
        const fontSize = 6;
        const text = 'Created for free using BillGST.in';
        doc.setFontSize(fontSize);
        doc.setTextColor(150);
        doc.text(text, pageWidth / 2, yPos + 3, { align: 'center' });
    } catch(e) { }
};

const autoSavePDF = async (doc, fileName, action = 'view') => {
    if (typeof window === 'undefined') return;
    try {
        const base64Data = doc.output('datauristring').split(',')[1];
        await downloadAndShareFile(base64Data, fileName, 'application/pdf', action);
    } catch (e) {
        console.error('PDF Save error', e);
        doc.save(fileName);
    }
};

export const generateEwayBillPDF = async (invoice, businessDetails, autoSave = true, action = 'view', toastId = null) => {
    try {
        if (!toastId) toastId = toast.loading('Generating E-Way Bill PDF...');

        const doc = new jsPDF({ orientation: 'p', unit: 'mm', format: 'a4' });
        const margin = 10;
        const pageWidth = doc.internal.pageSize.width;
        const pageHeight = doc.internal.pageSize.height;
        const contentWidth = pageWidth - (margin * 2);

        // Standard Font
        const font = 'helvetica';

        // --- Outer Border ---
        doc.setDrawColor(0, 0, 0);
        doc.setLineWidth(0.3);
        doc.rect(margin, margin, contentWidth, pageHeight - (margin * 2));

        // --- Header Section ---
        doc.setFontSize(14);
        doc.setFont(font, 'bold');
        doc.text('e-Way Bill', pageWidth / 2, margin + 8, { align: 'center' });

        doc.setFontSize(10);
        doc.setFont(font, 'normal');
        
        // Horizontal Line
        doc.setLineWidth(0.1);
        doc.line(margin, margin + 12, pageWidth - margin, margin + 12);

        // Date formatter helper
        const safeDate = (d) => {
            if (!d) return 'N/A';
            try {
                let dStr = String(d);
                if (dStr.includes('T')) dStr = dStr.split('T')[0];
                const date = new Date(dStr);
                if (isNaN(date.getTime())) return dStr.substring(0, 10);
                const dd = String(date.getDate()).padStart(2, '0');
                const mm = String(date.getMonth() + 1).padStart(2, '0');
                const yyyy = date.getFullYear();
                return `${dd}-${mm}-${yyyy}`;
            } catch(e) {
                return String(d).substring(0, 10);
            }
        };

        // --- EWB Details Top ---
        let currentY = margin + 18;
        
        doc.setFontSize(10);
        doc.setFont(font, 'bold');
        doc.text('E-Way Bill No:', margin + 5, currentY);
        doc.setFontSize(12);
        doc.text(invoice.eway_bill_no || 'N/A', margin + 35, currentY);

        doc.setFontSize(9);
        doc.setFontSize(9);
        doc.setFont(font, 'bold');
        doc.text('E-Way Bill Date:', pageWidth / 2 - 20, currentY);
        doc.setFont(font, 'normal');
        doc.text(safeDate(invoice.eway_bill_date || invoice.invoice_date), pageWidth / 2 + 5, currentY);

        currentY += 8;
        doc.setFont(font, 'bold');
        doc.text('Generated By:', margin + 5, currentY);
        doc.setFont(font, 'normal');
        doc.text(businessDetails.gstin || 'N/A', margin + 35, currentY);

        doc.setFont(font, 'bold');
        doc.text('Valid From:', pageWidth / 2 - 20, currentY);
        doc.setFont(font, 'normal');
        doc.text(safeDate(invoice.eway_bill_date || invoice.invoice_date), pageWidth / 2 + 5, currentY);

        currentY += 8;
        doc.setFont(font, 'bold');
        doc.text('Valid Until:', pageWidth / 2 - 20, currentY);
        doc.setFont(font, 'normal');
        // Simple 1 day validity approx if not specified
        const validDate = (invoice.eway_bill_date || invoice.invoice_date) ? new Date(invoice.eway_bill_date || invoice.invoice_date) : new Date();
        if (!isNaN(validDate.getTime())) validDate.setDate(validDate.getDate() + 1);
        doc.text(safeDate(validDate), pageWidth / 2 + 5, currentY);

        // QR Code in top right
        try {
            const qrText = `EWB:${invoice.eway_bill_no || 'N/A'}|GSTIN:${businessDetails.gstin || 'N/A'}|Date:${invoice.eway_bill_date || 'N/A'}`;
            const qrDataUrl = await QRCode.toDataURL(qrText, { margin: 0 });
            doc.addImage(qrDataUrl, 'PNG', pageWidth - margin - 25, margin + 15, 20, 20);
        } catch (e) {}

        currentY += 12;

        // --- PART A ---
        doc.setFillColor(230, 230, 230);
        doc.rect(margin, currentY, contentWidth, 8, 'F');
        doc.setFontSize(10);
        doc.setFont(font, 'bold');
        doc.text('PART - A', margin + 5, currentY + 5);
        currentY += 8;

        const partAYStart = currentY;
        doc.line(margin, currentY, pageWidth - margin, currentY);

        const partARows = [
            ['GSTIN of Supplier', businessDetails.gstin || 'URP'],
            ['Place of Dispatch', businessDetails.address ? businessDetails.address.substring(0, 30) : 'N/A'],
            ['GSTIN of Recipient', invoice.customer?.gstin || 'URP'],
            ['Place of Delivery', invoice.customer?.address ? invoice.customer.address.substring(0, 30) : 'N/A'],
            ['Document No.', invoice.invoice_number || 'N/A'],
            ['Document Date', safeDate(invoice.invoice_date)],
            ['Value of Goods', `Rs. ${Number(invoice.total_amount).toFixed(2)}`],
            ['HSN Code', invoice.items && invoice.items[0] ? (invoice.items[0].hsn_code || 'N/A') : 'N/A'],
            ['Reason for Transportation', 'Outward - Supply']
        ];

        let rY = currentY + 6;
        doc.setFontSize(9);
        partARows.forEach((row, i) => {
            doc.setFont(font, 'normal');
            doc.text(row[0], margin + 5, rY);
            doc.setFont(font, 'bold');
            doc.text(String(row[1]), margin + 60, rY);
            rY += 6;
        });

        currentY = rY + 4;
        
        // --- PART B ---
        doc.setFillColor(230, 230, 230);
        doc.rect(margin, currentY, contentWidth, 8, 'F');
        doc.setFontSize(10);
        doc.setFont(font, 'bold');
        doc.text('PART - B', margin + 5, currentY + 5);
        currentY += 8;

        autoTable(doc, {
            startY: currentY,
            head: [['Vehicle No.', 'From', 'Entered Date', 'Entered By', 'Multi Veh.Info']],
            body: [
                [
                    invoice.vehicle_no || '-',
                    businessDetails.address ? businessDetails.address.substring(0, 15) : '-',
                    safeDate(invoice.eway_bill_date || invoice.invoice_date),
                    businessDetails.gstin || '-',
                    '-'
                ]
            ],
            theme: 'grid',
            headStyles: { fillColor: [240, 240, 240], textColor: 0, fontStyle: 'bold', lineWidth: 0.1, lineColor: 0 },
            styles: { fontSize: 8, textColor: 0, lineWidth: 0.1, lineColor: 0 },
            margin: { left: margin, right: margin }
        });

        currentY = doc.lastAutoTable.finalY + 15;

        // Transport details summary
        doc.setFontSize(9);
        doc.setFont(font, 'bold');
        doc.text('Transportation Details:', margin + 2, currentY);
        currentY += 6;
        doc.setFont(font, 'normal');
        doc.text(`Transporter ID / Name: ${invoice.transporter_id || '-'} / ${invoice.transporter_name || '-'}`, margin + 5, currentY);
        currentY += 6;
        doc.text(`Distance: ${invoice.distance || '-'} Km`, margin + 5, currentY);
        currentY += 6;
        doc.text(`Mode: ${invoice.transport_mode || 'Road'}`, margin + 5, currentY);

        // Branding
        const isPremium = isUserPremium(businessDetails);
        if (!isPremium) {
            await drawFreeBranding(doc, false, pageWidth, pageHeight, pageHeight - margin - 5);
        }

        if (autoSave && typeof window !== 'undefined') {
            await autoSavePDF(doc, `EWayBill_${invoice.eway_bill_no || invoice.invoice_number || '001'}_${Date.now()}.pdf`, action);
        }

        toast.dismiss(toastId);
        return doc;
    } catch (e) {
        console.error('E-Way Bill PDF Generation Error:', e);
        if (toastId) toast.dismiss(toastId);
        return null;
    }
};
